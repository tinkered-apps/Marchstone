/* i18n.js: every sentence the app says, in English and Polish.
 *
 * No DOM in here, like geo.js and the rest, so the modules that build
 * sentences stay testable in Node. app.js picks the language at start-up and
 * when the header switch is used; everything else only asks t().
 *
 * An entry is a string with {name} slots, or a function of the same values
 * where the grammar hangs on a number. Polish has three plural forms, so a
 * count never gets a trailing "s" here: it goes through one() or pl(). */

export const LANGS = ['en', 'pl'];

let lang = 'en';

export function setLang(code) {
  lang = LANGS.includes(code) ? code : 'en';
  return lang;
}

export function getLang() { return lang; }

/* English: one, or everything else. */
const one = (n, single, many) => (n === 1 ? single : many);

/* Polish: 1 obszar, 2-4 obszary (but 12-14 obszarów), 5+ obszarów. */
export function pl(n, single, few, many) {
  if (n === 1) return single;
  const d = n % 10, h = n % 100;
  return d >= 2 && d <= 4 && (h < 12 || h > 14) ? few : many;
}

export function t(key, vars) {
  const entry = key in DICTS[lang] ? DICTS[lang][key] : DICTS.en[key];
  if (entry === undefined) return key;
  const v = vars || {};
  if (typeof entry === 'function') return entry(v);
  return entry.replace(/\{(\w+)\}/g, (m, k) => (k in v ? String(v[k]) : m));
}

